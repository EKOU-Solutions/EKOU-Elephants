def glyph(lvl):
    """Three rising bars; the filled count is the level, so the tag reads without colour."""
    bars = []
    for i, (x, h) in enumerate([(1, 6), (6, 10), (11, 14)]):
        y = 15 - h
        if lvl == 'unknown':
            bars.append(f'<rect x="{x + .5}" y="{y + .5}" width="3" height="{h - 1}" rx=".5" fill="none" stroke="currentColor" stroke-dasharray="2 1.5"/>')
        else:
            opacity = '' if i < steps[lvl] else ' opacity=".35"'
            bars.append(f'<rect x="{x}" y="{y}" width="4" height="{h}" rx="1" fill="currentColor"{opacity}/>')
    return f'<svg class="lvl" viewBox="0 0 16 16" aria-hidden="true">{"".join(bars)}</svg>'


def tag(lvl, large=False):
    size = ' el-tag-lg' if large else ''
    return f'<span class="el-tag el-tag-{lvl}{size}">{glyph(lvl)}{labels[lvl]}</span>'


def expand(html):
    html = re.sub(r'\{\{tag-lg:(\w+)\}\}', lambda m: tag(m.group(1), True), html)
    return re.sub(r'\{\{tag:(\w+)\}\}', lambda m: tag(m.group(1)), html)


