def finish(html, name):
    for key, value in replacements.items():
        html = html.replace(key, value)
    html = expand(html)
    leftover = re.findall(r'__[A-Z_]+__|\{\{[^}]+\}\}', html)
    assert not leftover, (name, leftover)
    html = html.replace('<!--LUCIDE-->', lucide)
    assert len(html.encode()) < 2_000_000, name
    (folder / name).write_text(html)
    return len(html.encode()) // 1024


